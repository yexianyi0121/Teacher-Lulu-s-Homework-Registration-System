/** 页内搜索：标题或正文命中（AC-29.2） */
export function searchManual(query: string): ManualSection[] {
  const q = query.trim();
  if (!q) return MANUAL;
  return MANUAL.filter((s) => {
    const hay = [s.title, s.intro ?? '', ...(s.steps ?? []), ...(s.tips ?? [])].join('\n');
    return hay.includes(q);
  });
}
